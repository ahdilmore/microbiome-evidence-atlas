import assert from 'node:assert/strict';
import fs from 'node:fs';
import {filterChanges,contextEvents,changes,featuresAtLevel} from './dist/sid-model.mjs';
const row={id:'a',name:'A',sgbs:['1'],values:[0,.001,.0009,.002,0],delta:.1};
assert.equal(filterChanges([row],{abundance:.1,minSamples:2})[0].present,2);
assert.equal(filterChanges([row],{abundance:0,minSamples:3})[0].present,3);
assert.equal(filterChanges([row],{abundance:0,minSamples:4}).length,0);
assert.equal(filterChanges([row],{abundance:0,minSamples:1,minDelta:.11}).length,0);
assert.equal(filterChanges([row],{abundance:0,minSamples:1,direction:'down'}).length,0);
const data=JSON.parse(fs.readFileSync('dist/sid-data.json'));
const rows=changes(featuresAtLevel(data),0,4),before=JSON.stringify(rows);
assert.ok(filterChanges(rows).length<rows.length);assert.equal(JSON.stringify(rows),before);
const events=JSON.parse(fs.readFileSync('dist/sid-events.json')).events;
const march=contextEvents(events,'2026-03-10','2026-03-27',0);
assert.ok(march.some(e=>e.title==='Cefazolin'));
assert.ok(!march.some(e=>e.title==='Dostarlimab'));
assert.ok(contextEvents(events,'2026-03-10','2026-03-27',7).some(e=>e.date==='2026-03-09'&&e.relation==='Before window'));
assert.ok(contextEvents(events,'2025-10-22','2025-10-22',0).some(e=>e.title==='Dalbavancin'&&e.relation==='Overlaps window'));
assert.ok(!contextEvents(events,'2026-03-10','2026-03-10',0).some(e=>e.title==='Cefazolin'));
console.log('Passed threshold boundaries, non-detection, prevalence, delta/direction filters, unchanged abundances, treatment-range overlap and padded event boundaries.');
